#!/usr/bin/env python3

def suma(a, b):
    return a + b

def resta(a, b):
    return a - b

def multi(a, b):
    return a * b

def division(a, b):
    return a / b



if __name__ == "__main__":
    a = 10
    b = 5
    print(suma(a, b))
    print(resta(a, b))
    print(multi(a, b))
    print(division(a, b))
